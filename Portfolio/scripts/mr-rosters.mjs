// Turns the CCLMR roster spreadsheet into src/mr_scraper/data/rosters.ts, which
// the MR_Scraper page offers as a team picker. Run after the sheet changes:
//
//   npm run mr:rosters
//
// Sheet layout: each team is a block. The team name sits in a header cell
// merged across two rows (e.g. B2:D3), and its players are listed in the same
// column underneath, one per row, until the first empty cell.
//
// An .xlsx file is a zip of XML files, so this reads it with Node's own zlib
// rather than pulling in a spreadsheet library.

import { readFileSync, writeFileSync } from "node:fs";
import { inflateRawSync } from "node:zlib";

const SOURCE = "src/mr_scraper/data/CCLMR - Fall 2026 Rosters Information.xlsx";
const OUTPUT = "src/mr_scraper/data/rosters.ts";

/** Every file in a zip archive, by name, from its central directory. */
function unzip(buf) {
  let eocd = buf.length - 22;
  while (eocd >= 0 && buf.readUInt32LE(eocd) !== 0x06054b50) eocd--;
  if (eocd < 0) throw new Error("not a zip file");
  const count = buf.readUInt16LE(eocd + 10);
  let p = buf.readUInt32LE(eocd + 16);
  const files = new Map();
  for (let i = 0; i < count; i++) {
    const method = buf.readUInt16LE(p + 10);
    const size = buf.readUInt32LE(p + 20);
    const nameLen = buf.readUInt16LE(p + 28);
    const extraLen = buf.readUInt16LE(p + 30);
    const commentLen = buf.readUInt16LE(p + 32);
    const local = buf.readUInt32LE(p + 42);
    const name = buf.toString("utf8", p + 46, p + 46 + nameLen);
    const start = local + 30 + buf.readUInt16LE(local + 26) + buf.readUInt16LE(local + 28);
    const data = buf.subarray(start, start + size);
    files.set(name, method === 8 ? inflateRawSync(data) : data);
    p += 46 + nameLen + extraLen + commentLen;
  }
  return files;
}

const decode = (s) =>
  s
    .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)))
    .replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(Number(d)))
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&amp;/g, "&");

/** The text of every <t> run inside a fragment (rich text splits one string into several runs). */
const runs = (xml) => [...xml.matchAll(/<t(?:\s[^>]*)?>([^<]*)<\/t>/g)].map((m) => decode(m[1])).join("");

const files = unzip(readFileSync(SOURCE));
const shared = [...(files.get("xl/sharedStrings.xml")?.toString("utf8") ?? "").matchAll(/<si>([\s\S]*?)<\/si>/g)].map((m) => runs(m[1]));
const sheet = files.get("xl/worksheets/sheet1.xml").toString("utf8");

/** Cell text by reference ("B4"). */
const cells = new Map();
for (const m of sheet.matchAll(/<c r="([A-Z]+\d+)"([^>]*?)(?:\/>|>([\s\S]*?)<\/c>)/g)) {
  const [, ref, attrs, body = ""] = m;
  const type = /\bt="([^"]+)"/.exec(attrs)?.[1];
  const v = /<v>([\s\S]*?)<\/v>/.exec(body)?.[1];
  const text = type === "s" && v !== undefined ? shared[Number(v)] : type === "inlineStr" ? runs(body) : v !== undefined ? decode(v) : "";
  if (text.trim()) cells.set(ref, text);
}

const split = (ref) => {
  const [, col, row] = /^([A-Z]+)(\d+)$/.exec(ref);
  return { col, row: Number(row) };
};

// Team headers: cells merged across exactly two rows, read in sheet order (top to bottom, then left to right).
const headers = [...sheet.matchAll(/<mergeCell ref="([A-Z]+\d+):([A-Z]+\d+)"/g)]
  .map(([, from, to]) => ({ from: split(from), to: split(to) }))
  .filter(({ from, to }) => to.row === from.row + 1 && cells.has(`${from.col}${from.row}`))
  .map(({ from }) => from)
  .sort((a, b) => a.row - b.row || a.col.length - b.col.length || a.col.localeCompare(b.col));

const rosters = headers.map(({ col, row }) => {
  // "ST CLAIR COLLEGE - A ()" -> "ST CLAIR COLLEGE - A": the trailing brackets hold an unfilled team id.
  const team = cells.get(`${col}${row}`).replace(/\s*\([^)]*\)\s*$/, "").trim();
  const players = [];
  for (let r = row + 2; cells.has(`${col}${r}`); r++) players.push(cells.get(`${col}${r}`).trim());
  return { team, players };
});

const body = rosters.map((r) => `  { team: ${JSON.stringify(r.team)}, players: ${JSON.stringify(r.players)} },`).join("\n");
writeFileSync(
  OUTPUT,
  `// Generated by scripts/mr-rosters.mjs from "${SOURCE.split("/").pop()}".
// Do not edit by hand: update the spreadsheet and run \`npm run mr:rosters\`.

export type Roster = { team: string; players: string[] };

export const ROSTERS: Roster[] = [
${body}
];
`,
  "utf8",
);
console.log(`${rosters.length} teams, ${rosters.reduce((n, r) => n + r.players.length, 0)} players -> ${OUTPUT}`);
